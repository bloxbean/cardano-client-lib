// Deterministic byte strings: sha256("<seed>/<i>/<tag>") truncated to a length derived from the digest.
function bytes(seed, i, tag, minLen, maxLen) {
  const h = createHash('sha256').update(`${seed}/${i}/${tag}`).digest();
  const len = minLen + (h[0] % (maxLen - minLen + 1));
  return Buffer.concat([h, createHash('sha256').update(h).digest()]).subarray(0, len);
}

function stepsJson(proof) {
  return proof.toJSON();
}

// Keep the exact CBOR (indefinite-length framing) for the first few proofs of each trie only.
function withCbor(index, vector, proof) {
  if (index < 3) vector.cbor = proof.toCBOR().toString('hex');
  return vector;
}

async function vectorsFor(name, pairs, absentKeys, maxPresent) {
  const trie = await Trie.fromList(pairs.map(([key, value]) => ({ key, value })));
  const out = {
    name,
    root: trie.hash ? trie.hash.toString('hex') : null,
    entries: pairs.map(([k, v]) => [Buffer.from(k).toString('hex'), Buffer.from(v).toString('hex')]),
    present: [],
    absent: [],
  };
  const step = Math.max(1, Math.floor(pairs.length / maxPresent));
  for (let i = 0; i < pairs.length; i += step) {
    const [k] = pairs[i];
    const proof = await trie.prove(k);
    out.present.push(withCbor(out.present.length, { key: Buffer.from(k).toString('hex'), proof: stepsJson(proof) }, proof));
  }
  if (!trie.isEmpty()) {
    for (const k of absentKeys) {
      const proof = await trie.prove(k, true);
      out.absent.push(withCbor(out.absent.length, { key: Buffer.from(k).toString('hex'), proof: stepsJson(proof) }, proof));
    }
  }
  return out;
}

const tries = [];
tries.push(await vectorsFor('fruits', FRUITS.map(([k, v]) => [Buffer.from(k), Buffer.from(v)]),
  Array.from({ length: 200 }, (_, i) => Buffer.from(`missing-${i}`)), 30));

for (const size of [1, 2, 3, 4, 5, 8, 16, 33, 100, 257, 1000]) {
  const seen = new Set();
  const pairs = [];
  for (let i = 0; pairs.length < size; i++) {
    const k = bytes(size, i, 'k', 1, 24);
    if (seen.has(k.toString('hex'))) continue;
    seen.add(k.toString('hex'));
    pairs.push([k, bytes(size, i, 'v', 0, 16)]);
  }
  const absent = [];
  for (let i = 0; absent.length < 60; i++) {
    const k = bytes(size, i, 'absent', 1, 24);
    if (!seen.has(k.toString('hex'))) absent.push(k);
  }
  tries.push(await vectorsFor(`random-${size}`, pairs, absent, 60));
}

const seq = Array.from({ length: 1000 }, (_, i) => [Buffer.from(`key-${i}`), Buffer.from(`value-${i}`)]);
tries.push(await vectorsFor('sequential-1000', seq, Array.from({ length: 200 }, (_, i) => Buffer.from(`missing-${i}`)), 60));

